export * as MemoryManifest from "./memory-manifest"

import path from "node:path"
import type { MemoryV2 } from "./memory-v2"

export type Budget = {
  maxBytes: number
  maxEntries: number
  maxDescriptionBytes: number
  includeObservations: boolean
  slugTail: boolean
}
export type Entry = { path: string; content: string; modified: number; readCount: number }

export function budget(compact = false): Budget {
  return {
    maxBytes: 8192,
    maxEntries: compact ? 512 : 64,
    maxDescriptionBytes: compact ? 0 : 512,
    includeObservations: !compact,
    slugTail: compact,
  }
}

// Use UTF-8 bytes for every limit, including headers and section separators.
// A decoder in streaming mode drops an incomplete final code point.
export function truncate(text: string, bytes: number) {
  return new TextDecoder().decode(Buffer.from(text).subarray(0, bytes), { stream: true })
}

export function compare(left: Entry, right: Entry, compact = false) {
  const topic = left.path.startsWith("topics/")
  return (
    Number(right.path.startsWith("topics/")) - Number(topic) ||
    (topic
      ? (compact ? right.readCount - left.readCount : 0) ||
        Buffer.compare(Buffer.from(left.path), Buffer.from(right.path))
      : right.modified - left.modified || Buffer.compare(Buffer.from(right.path), Buffer.from(left.path)))
  )
}

export function render(root: Pick<MemoryV2.Root, "path" | "scope">, entries: Entry[], requested = budget()) {
  const limits = {
    ...requested,
    maxBytes: Math.min(16384, Math.max(0, Math.floor(requested.maxBytes))),
    maxEntries: Math.min(512, Math.max(0, Math.floor(requested.maxEntries))),
    maxDescriptionBytes: Math.min(512, Math.max(0, Math.floor(requested.maxDescriptionBytes))),
  }
  const selected = entries
    .filter((entry) => limits.includeObservations || entry.path.startsWith("topics/"))
    .toSorted((left, right) => compare(left, right, limits.slugTail))
  const heading = `# ${root.scope === "global" ? "Global" : "Workspace"} memory index\n\n> Generated by Apexo. Do not edit this file directly.\n> Paths are relative to \`${inline(root.path)}\`.\n`
  const state = {
    content: truncate(heading, limits.maxBytes),
    kind: "",
    paths: [] as string[],
    tail: [] as Entry[],
    byteLimited: Buffer.byteLength(heading) > limits.maxBytes,
  }
  if (!state.byteLimited) {
    for (const entry of selected.slice(0, limits.maxEntries)) {
      const topic = entry.path.startsWith("topics/")
      const kind = topic ? "Topics" : "Pending observations"
      const summary = summarize(entry)
      const description = truncate(summary.description, limits.maxDescriptionBytes)
      const addition = `${state.kind === kind ? "" : `\n## ${kind}\n`}\n- **${summary.title}**${topic && description ? ` — ${description}` : ""} (\`${inline(entry.path)}\`)\n`
      if (
        Buffer.byteLength(state.content + addition) >
        (limits.slugTail ? Math.floor((limits.maxBytes * 3) / 4) : limits.maxBytes)
      ) {
        if (limits.slugTail) {
          state.tail.push(entry)
          continue
        }
        state.byteLimited = true
        // Newest observations have priority. Do not backfill with smaller old notes.
        if (!topic) break
        continue
      }
      state.content += addition
      state.kind = kind
      state.paths.push(entry.path)
    }
  }
  if (!selected.length) {
    const empty = `${heading}\nNo ${limits.includeObservations ? "memory files" : "topics"} have been recorded yet.\n`
    state.content = truncate(empty, limits.maxBytes)
    state.byteLimited = Buffer.byteLength(empty) > limits.maxBytes
  }
  if (limits.slugTail && state.tail.length) {
    const prefix = "\n## More topics\n\nBy file name under `topics/`:"
    const tail = { bytes: Buffer.byteLength(state.content + prefix) + 1, slugs: [] as string[] }
    for (const entry of state.tail) {
      const slug = inline(entry.path.replace(/^topics\//, "").replace(/\.md$/, ""))
      const size = Buffer.byteLength(slug) + (tail.slugs.length ? 2 : 1)
      if (tail.bytes + size > Math.max(0, limits.maxBytes - 128)) {
        state.byteLimited = true
        break
      }
      tail.bytes += size
      tail.slugs.push(slug)
      state.paths.push(entry.path)
    }
    if (tail.slugs.length)
      state.content += `${prefix} ${tail.slugs.sort((a, b) => Buffer.compare(Buffer.from(a), Buffer.from(b))).join(", ")}\n`
    const omitted = selected.length - state.paths.length
    if (omitted) {
      const note = `\n${omitted} more topics are not listed.\n`
      if (Buffer.byteLength(state.content + note) <= limits.maxBytes) state.content += note
    }
  }
  return {
    content: state.content,
    paths: state.paths,
    discoveredEntries: selected.length,
    includedEntries: state.paths.length,
    truncated: state.byteLimited || selected.length > state.paths.length,
  }
}

function summarize(entry: Entry) {
  const result = { title: "", description: "" }
  for (const line of truncate(entry.content, 64 * 1024)
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)) {
    if (!result.title && line.startsWith("#")) {
      result.title = line.replace(/^#+/, "").trim()
      continue
    }
    if (!result.description && !/^(#|<!--|>)/.test(line)) result.description = truncate(line, 512)
    if (result.title && result.description) break
  }
  return {
    title: inline(truncate(result.title || path.posix.basename(entry.path, ".md"), 512)),
    description: inline(result.description),
  }
}

function inline(value: string) {
  return value.replace(/[\n\r]/g, " ").replaceAll("`", "'")
}
